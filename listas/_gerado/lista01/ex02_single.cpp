    assert(falso::nivel(25) == LOW);

    // cada alterna escreve no pino exatamente uma vez
    falso::reinicia();
    Led contado(26);
    contado.inicia();                       // 1 escrita (desliga)
    contado.alterna();
    contado.alterna();
